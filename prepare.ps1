$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot
$www = Join-Path $PSScriptRoot 'app\src\main\assets\www'
$swf = Join-Path $www 'arcane.swf'
if (!(Test-Path $swf)) { throw "Missing arcane.swf. Copy your own legally obtained game SWF to: $swf" }

# Download the official Ruffle NPM self-hosted release into the private local build.
$version = '0.7.1'
$ruffleDest = Join-Path $www 'ruffle'
$archive = Join-Path $env:TEMP "arcane-ruffle-$version.tgz"
$extract = Join-Path $env:TEMP "arcane-ruffle-extract-$version"
if (!(Test-Path (Join-Path $ruffleDest 'ruffle.js'))) {
    Write-Host "Downloading Ruffle $version from npmjs.org..."
    Invoke-WebRequest "https://registry.npmjs.org/@ruffle-rs/ruffle/-/ruffle-$version.tgz" -OutFile $archive
    if (Test-Path $extract) { Remove-Item $extract -Recurse -Force }
    New-Item -ItemType Directory -Path $extract -Force | Out-Null
    tar -xzf $archive -C $extract
    $ruffleJs = Get-ChildItem -Path $extract -Recurse -File -Filter 'ruffle.js' | Select-Object -First 1
    if (!$ruffleJs) { throw "Ruffle download didn't contain ruffle.js" }
    New-Item -ItemType Directory -Path $ruffleDest -Force | Out-Null
    Copy-Item (Join-Path $ruffleJs.DirectoryName '*') $ruffleDest -Recurse -Force
}
Write-Host 'Ruffle assets ready.'

# Locate the Windows Android SDK and Java installed with Android Studio.
$sdk = Join-Path $env:LOCALAPPDATA 'Android\Sdk'
if (!(Test-Path $sdk)) { throw "Android SDK not found at $sdk" }
$env:ANDROID_HOME = $sdk
$sdkUnix = $sdk.Replace('\','/')
Set-Content -Path 'local.properties' -Value "sdk.dir=$sdkUnix"
if (!$env:JAVA_HOME -or !(Test-Path (Join-Path $env:JAVA_HOME 'bin\java.exe'))) {
    $androidJbr = Join-Path $env:ProgramFiles 'Android\Android Studio\jbr'
    if (Test-Path $androidJbr) { $env:JAVA_HOME = $androidJbr }
}
if (!$env:JAVA_HOME) { throw 'Java not found. Install Android Studio with bundled JDK 17.' }
$env:PATH = (Join-Path $env:JAVA_HOME 'bin') + ';' + $env:PATH

# Bootstrap an official Gradle wrapper once. Gradle's standard wrapper scripts/JAR
# are generated by Gradle itself rather than fabricated or downloaded from mirrors.
if (!(Test-Path 'gradlew.bat')) {
    $bootstrapDir = Join-Path $PSScriptRoot '.bootstrap'
    New-Item -ItemType Directory -Path $bootstrapDir -Force | Out-Null
    $gradleZip = Join-Path $bootstrapDir 'gradle-8.11.1-bin.zip'
    if (!(Test-Path $gradleZip)) {
        Write-Host 'Downloading official Gradle 8.11.1 bootstrap (approx. 130 MB)...'
        Invoke-WebRequest 'https://services.gradle.org/distributions/gradle-8.11.1-bin.zip' -OutFile $gradleZip
    }
    if (!(Test-Path (Join-Path $bootstrapDir 'gradle-8.11.1\bin\gradle.bat'))) {
        Expand-Archive $gradleZip -DestinationPath $bootstrapDir -Force
    }
    & (Join-Path $bootstrapDir 'gradle-8.11.1\bin\gradle.bat') wrapper --gradle-version 8.11.1 --distribution-type bin
    if ($LASTEXITCODE -ne 0) { throw "Gradle wrapper generation failed" }
}
Write-Host 'Starter project ready. Open this folder in Android Studio and build the debug APK.'
